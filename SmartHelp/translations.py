def get_text(key, lang="uz", default=None):
    lang_dict = MESSAGES.get(lang, MESSAGES.get("uz", {}))
    if key in lang_dict:
        return lang_dict[key]
    # Fallback to uz
    uz_dict = MESSAGES.get("uz", {})
    return uz_dict.get(key, default if default is not None else key)

def get_role_name(role, lang="uz"):
    return ROLES_TRANSLATIONS.get(lang, ROLES_TRANSLATIONS["uz"]).get(role, role)

def get_status_name(status, lang="uz"):
    return STATUSES_TRANSLATIONS.get(lang, STATUSES_TRANSLATIONS["uz"]).get(status, status)

def get_category_name(category, lang="uz"):
    return CATEGORIES_TRANSLATIONS.get(lang, CATEGORIES_TRANSLATIONS["uz"]).get(category, category)
